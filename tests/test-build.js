const fs = require('node:fs');
const assert = require('node:assert/strict');
const path = require('node:path');
const vm = require('node:vm');
const base = path.join(__dirname,'..');
const source = fs.readFileSync(path.join(base,'src/engine.js'),'utf8');
const generated = fs.readFileSync(path.join(base,'index.html'),'utf8');
const extension = fs.readFileSync(path.join(base,'extension/engine.js'),'utf8');
const manifest = JSON.parse(fs.readFileSync(path.join(base,'extension/manifest.json'),'utf8'));
assert.ok(source.startsWith('/* Mudra Smart Cursor'));
assert.equal(source,extension);
assert.ok(generated.includes('const ENGINE_SOURCE = '));
assert.ok(generated.includes('/*MUDRA_PRESETS*/null'));
assert.ok(generated.includes('rebuild()'));
const start = generated.indexOf('<script>');
const end = generated.indexOf('</script>', start + 8);
assert.ok(start >= 0 && end > start, 'HTML must contain an inline installation script');
const inlineScript = generated.slice(start + 8, end);

new vm.Script(inlineScript, {filename:'landing-inline.js'});
new vm.Script(source.replace('/*MUDRA_PRESETS*/null', JSON.stringify({radius:30})), {filename:'bookmarklet.js'});
assert.ok(source.includes('requestPointerLock'));
assert.ok(!source.includes('navigator.bluetooth'), 'browser must not scan BLE');
assert.ok(!source.includes('requestDevice('), 'no browser Bluetooth discovery');
assert.ok(!source.includes('getPrimaryService('), 'GATT must stay in native companion');
assert.ok(source.includes('/api/status'), 'read native local helper status');
assert.ok(source.includes("targetAddressSpace:'loopback'"), 'remote pages declare loopback address space');
assert.ok(source.includes("new Request('/api/status'"), 'local companion page uses same-origin API');
assert.ok(generated.includes('queueMicrotask(activateSmartCursorOnThisPage)'), 'native local page starts cursor automatically');
assert.ok(source.includes('startMonitoring()'), 'automatic local helper monitoring must be available');
assert.ok(source.includes("scan(); startMonitoring();"), 'opening cursor starts local helper check');
assert.ok(!source.includes('Stop monitoring'), 'no misleading stop button while companion offline');
assert.ok(source.includes('Firmware Air Touch OFF — normal HID mouse.'), 'FW off restores HID');
assert.ok(source.includes('root.elementFromPoint'), 'virtual panel controls reachable');
assert.ok(source.includes('checkShake(ev.movementX'), 'shake recenter intact');
assert.ok(source.includes('clickAssist: false'));
assert.ok(source.includes('dwell: false'));
assert.equal(manifest.manifest_version,3);
assert.deepEqual(manifest.permissions,['activeTab','scripting']);
assert.deepEqual(manifest.host_permissions,['http://127.0.0.1:8765/*']);
assert.ok(source.includes('fetch(request)'));
assert.ok(!source.includes('XMLHttpRequest'));
console.log('Static build and security tests passed.');
