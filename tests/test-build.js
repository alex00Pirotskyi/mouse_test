const fs = require('node:fs');
const assert = require('node:assert/strict');
const path = require('node:path');
const vm = require('node:vm');
const base = path.join(__dirname,'..');
const source = fs.readFileSync(path.join(base,'src/engine.js'),'utf8');
const generated = fs.readFileSync(path.join(base,'index.html'),'utf8');
const extension = fs.readFileSync(path.join(base,'extension/engine.js'),'utf8');
const manifest = JSON.parse(fs.readFileSync(path.join(base,'extension/manifest.json'),'utf8'));
assert.ok(source.startsWith('/* Mudra Smart Cursor'));
assert.equal(source,extension);
assert.ok(generated.includes('const ENGINE_SOURCE = '));
assert.ok(generated.includes('/*MUDRA_PRESETS*/null'));
assert.ok(generated.includes('rebuild()'));
const start = generated.indexOf('<script>');
const end = generated.indexOf('</script>', start + 8);
assert.ok(start >= 0 && end > start, 'HTML must contain an inline installation script');
const inlineScript = generated.slice(start + 8, end);

new vm.Script(inlineScript, {filename:'landing-inline.js'});
new vm.Script(source.replace('/*MUDRA_PRESETS*/null', JSON.stringify({radius:30})), {filename:'bookmarklet.js'});
assert.ok(source.includes('requestPointerLock'));
const parserStart = source.indexOf('  function decodeSystemMap(value) {');
const parserEnd = source.indexOf('  function onFirmwareNotification(', parserStart);
assert.ok(parserStart >= 0 && parserEnd > parserStart, 'map parser must be present');
const parseMap = new Function('value', source.slice(parserStart,parserEnd) + 'return decodeSystemMap(value);');
const map = new Uint8Array(27);
map[0]=1; map[2]=1; map[15]=1;
assert.deepEqual(parseMap(map),{airTouch:true,specific:1,imuMaster:1});
map[15]=0;
assert.equal(parseMap(map).airTouch,false,'Air Touch OFF');
map[15]=1; map[2]=0;
assert.equal(parseMap(map).airTouch,false,'IMU master OFF');
map[2]=1;map[15]=17;
assert.equal(parseMap(map),null,'Invalid firmware flag must not enable virtual');
assert.equal(parseMap(new Uint8Array(21)),null,'Legacy maps without Air Touch flag remain unknown');
assert.ok(!source.includes('topEdgeTravel >= 48'), 'top-edge escape must be removed');
assert.ok(source.includes('decodeSystemMap(value)'), 'must parse only firmware system map');
assert.ok(source.includes('value[15]'), 'Air Touch flag must be imuSpecific index 10');
assert.ok(source.includes('0x75,0x00,0x00'), 'must request real firmware map');
assert.ok(source.includes('getPrimaryService(0x180f)'), 'must read standard battery service');
assert.ok(source.includes('checkShake(ev.movementX'), 'must detect shake with HID movement');
assert.ok(source.includes('root.elementFromPoint'), 'virtual clicks must reach the Mudra control panel');
assert.ok(source.includes('Firmware Air Touch OFF. Normal HID cursor.'));
assert.ok(source.includes('cmd.startNotifications()'));
assert.ok(source.includes('clickAssist: false'));
assert.ok(source.includes('dwell: false'));
assert.equal(manifest.manifest_version,3);
assert.deepEqual(manifest.permissions,['activeTab','scripting']);
assert.ok(!source.includes('fetch('));
assert.ok(!source.includes('XMLHttpRequest'));
console.log('Static build and security tests passed.');
