const fs = require('node:fs');
const assert = require('node:assert/strict');
const vm = require('node:vm');
const html = fs.readFileSync('ble-probe.html','utf8');
const page = fs.readFileSync('index.html','utf8');
assert.ok(page.includes('ble-probe.html'), 'Landing page must expose no-install test');
assert.ok(html.includes('No download, desktop companion'), 'Probe must explain no app needed');
const match = html.match(/<script>([\s\S]*?)<\/script>/);
assert.ok(match,'Must contain no-dependency executable browser script');
const code = match[1];
new vm.Script(code,{filename:'ble-probe-inline.js'});
assert.ok(code.includes('bluetooth.getDevices()'), 'Must check previously browser-authorized devices');
assert.ok(code.includes('bluetooth.requestDevice('), 'Must allow one-time filtered authorization');
assert.ok(code.includes('optionalServices:[0xfff0,0x180f]'), 'Grant Mudra and optional battery services');
assert.ok(!code.includes('acceptAllDevices:true'), 'No unfiltered device chooser');
assert.ok(!code.includes('scanForPeripherals'), 'No native BLE advertisement scan');
assert.ok(!code.includes('.gatt.disconnect()'), 'Never disconnect OS-linked GATT during feasibility test');
assert.ok(code.includes("new Uint8Array([0x75,0x00,0x00])"), 'Must request read-only system map');
assert.ok(code.includes('startNotifications()'), 'Must subscribe to firmware notifications');
assert.ok(code.includes('getPrimaryService(0xfff0)'), 'Mudra FFF0 service must be read');
assert.ok(code.includes('getCharacteristic(0xfff1)'), 'Mudra FFF1 characteristic must be used');
assert.ok(!html.includes('127.0.0.1'), 'No local companion required');
const a=code.indexOf('function boolByte(');
const b=code.indexOf('function onValue(',a);
assert.ok(a>=0 && b>a,'System map decoder must be testable');
const parse=new Function('bytes',code.slice(a,b)+'return parseSystemMap(bytes);');
const current=new Uint8Array(26);
current[0]=1;current[2]=1;current[15]=1;current[24]=0x22;current[25]=1;
assert.equal(parse(current).airTouch,true);
current[15]=0;
assert.equal(parse(current).airTouch,false);
current[15]=1;current[2]=0;
assert.equal(parse(current).airTouch,false,'IMU master disables Air Touch');
current[2]=1;current[15]=5;
assert.equal(parse(current).valid,false,'Invalid state rejected');
const legacy=new Uint8Array(21);legacy[0]=1;
assert.equal(parse(legacy).airTouch,null,'Legacy map Air Touch must be unknown');
const short=new Uint8Array(20);short[0]=1;
assert.equal(parse(short).valid,false,'Truncated map rejected');
const old27=new Uint8Array(27);
old27[0]=1;old27[2]=1;old27[15]=1;old27[24]=0x22;old27[25]=1;
assert.equal(parse(old27).sncLength,5);
const new27=new Uint8Array(27);
new27[0]=1;new27[2]=1;new27[15]=1;new27[24]=1;new27[25]=0x22;new27[26]=1;
assert.equal(parse(new27).sncLength,6);
const ambiguous=new Uint8Array(27);
ambiguous[0]=1;ambiguous[2]=1;ambiguous[15]=1;
assert.equal(parse(ambiguous).valid,false);
console.log('Web Bluetooth no-install probe: syntax, permission flow and system-map decoder passed.');
